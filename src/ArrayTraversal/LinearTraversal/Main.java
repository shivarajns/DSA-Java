package ArrayTraversal.LinearTraversal;

public class Main {

    public static void main(String[] args) {

        System.out.println("Linear Traversal of an Array");

        int[] arr = {10,3,54,5,6,3,223,456};
        int n = arr.length;

        for(int i=0; i<n ; i++){
            System.out.print(arr[i]+" ");
        }
    }
}
